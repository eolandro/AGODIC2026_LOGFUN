% --- auxiliares ---

% Hermano: comparte al menos un progenitor
hermano_a(Ego, Persona) :-
    progenitor_a(Ego, Padre),
    progenitor_a(Persona, Padre),
    Ego \== Persona.


bisabuelo_a(Ego, Persona) :-
    abuelo_a(Ego, Padre),
    progenitor_a(Padre, Persona).


% --- Predicados  R001 ---

% Esposo de una hija de Ego (padre de un nieto de Ego)
yerno(Ego, Persona) :-
    progenitor_a(Hijo_a, Ego),
    progenitor_a(Nieto, Hijo_a),
    progenitor_a(Nieto, Persona),
    Persona \== Hijo_a,
    Persona \== Ego,
    hombre(Persona), !.

bisnieto_a(Ego, Persona) :-
    bisabuelo_a(Persona, Ego).

abuelo_a(Ego, Persona) :-
    progenitor_a(Ego, Padre),
    progenitor_a(Padre, Persona).

% Nieto de un hermano de Ego
sobrino_a_nieto(Ego, Persona) :-
    hermano_a(Ego, Hermano),
    progenitor_a(Hijo, Hermano),
    progenitor_a(Persona, Hijo), !.

% Hermano de un bisabuelo de Ego
tio_bisabuelo_a(Ego, Persona) :-
    bisabuelo_a(Ego, Bisabuelo),
    hermano_a(Bisabuelo, Persona), !.


% =============================================================================
% R002: DESCENDIENTE
% descendiente(Ego, Persona): Ego es descendiente de Persona
% =============================================================================

descendiente(Ego, Persona) :-
    progenitor_a(Ego, Persona).

descendiente(Ego, Persona) :-
    progenitor_a(Ego, Padre),
    descendiente(Padre, Persona).


% =============================================================================
% R003: DESCENDIENTES
% =============================================================================

descendientes(Ego, ListaDescendientes) :-
    findall(Desc, descendiente(Desc, Ego), ListaTemp),
    sort(ListaTemp, ListaDescendientes).


% =============================================================================
% R004: SECUENCIA
% f(0) = 7; f(n) = 2 * f(n-1) + 3
% =============================================================================

seq0(0, 7) :- !.
seq0(N, R) :-
    N > 0,
    N1 is N - 1,
    seq0(N1, R1),
    R is (2 * R1) + 3.


